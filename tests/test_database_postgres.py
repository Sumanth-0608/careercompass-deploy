import re

import pytest

import database


def test_schema_uses_postgresql_identity_and_boolean_syntax():
    with open(database.os.path.join(database.os.path.dirname(__file__), "..", "schema.sql"), encoding="utf-8") as schema_file:
        schema = schema_file.read()

    assert "PRAGMA" not in schema.upper()
    assert "AUTOINCREMENT" not in schema.upper()
    assert schema.count("GENERATED BY DEFAULT AS IDENTITY") == 16
    assert re.search(r"BOOLEAN NOT NULL DEFAULT (TRUE|FALSE)", schema)


def test_postgres_cursor_translates_qmark_parameters():
    class Cursor:
        def execute(self, query, params):
            self.query = query
            self.params = params

    cursor = Cursor()
    database._PostgresCursor(cursor).execute("SELECT * FROM careers WHERE id = ?", (7,))

    assert cursor.query == "SELECT * FROM careers WHERE id = %s"
    assert cursor.params == (7,)


def test_vercel_init_uses_database_url_without_filesystem_writes(monkeypatch):
    class Cursor:
        def execute(self, query, params=None):
            self.query = query
            self.params = params

        def fetchone(self):
            return {"count": 1}

    class Connection:
        def __init__(self):
            self.executed = []
            self.cursor_instance = Cursor()

        def execute(self, query, params=None, **kwargs):
            self.executed.append((query, params, kwargs))
            return self.cursor_instance

        def cursor(self):
            return self.cursor_instance

        def commit(self):
            self.committed = True

        def rollback(self):
            self.rolled_back = True

        def close(self):
            self.closed = True

    connection = Connection()
    monkeypatch.setenv("VERCEL", "1")
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:secret@example.invalid/db")
    monkeypatch.setattr(database, "_connect", lambda target: connection)
    monkeypatch.setattr(database.os, "makedirs", lambda *args, **kwargs: pytest.fail("filesystem write attempted"))
    monkeypatch.setattr(database.os, "remove", lambda *args, **kwargs: pytest.fail("database file removal attempted"))
    monkeypatch.setattr(database, "seed_additional_careers", lambda conn: None)
    monkeypatch.setattr(database, "seed_opportunities", lambda conn: None)
    monkeypatch.setattr(database, "seed_career_quotes", lambda conn: None)
    monkeypatch.setattr(database, "seed_appointments", lambda conn: None)

    database.init_db(reset=True)

    assert connection.executed[0][0] == "SELECT pg_advisory_xact_lock(?)"
    assert any("GENERATED BY DEFAULT AS IDENTITY" in call[0] for call in connection.executed)
    assert connection.executed[-1][2] == {"prepare": False}
    assert connection.committed
    assert connection.closed


def test_vercel_requires_database_url_without_exposing_credentials(monkeypatch):
    monkeypatch.setenv("VERCEL", "1")
    monkeypatch.delenv("DATABASE_URL", raising=False)

    with pytest.raises(RuntimeError, match="DATABASE_URL is required on Vercel") as error:
        database._resolve_database_target()

    assert "secret" not in str(error.value).lower()